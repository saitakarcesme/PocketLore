"""Constructed parser fixtures, never factual corpus. Run with pinned local test tools."""
import hashlib, io, json
from pathlib import Path
from reportlab.pdfgen.canvas import Canvas
from reportlab.lib.utils import ImageReader
from PIL import Image
from pypdf import PdfReader, PdfWriter
ROOT=Path(__file__).resolve().parents[3]
out=ROOT/'downloads/documents-fixtures';out.mkdir(parents=True,exist_ok=True)
files={'notes.txt':'Citrine notebook 🌍. The violet sample is labelled drawer seven.\n',
       'notes.md':'# Feldspar field notes\n\nA **private** observation, not a public license.\n',
       'quoted.csv':'name,description,count\r\n"Citrine, violet","He said ""hello""\nand continued",7\r\nQuartz,clear,2\r\n',
       'nested.json':'{"samples":[{"name":"Tourmaline","count":3}],"escaped":"line\\nnext","emoji":"🌍"}\n'}
for name,value in files.items():(out/name).write_bytes(value.encode())
def pdf(name,kind):
    buf=io.BytesIO();c=Canvas(buf,invariant=1)
    if kind=='text':c.drawString(72,720,'Amethyst notebook: sample stored in drawer nine.')
    if kind=='image':c.drawImage(ImageReader(Image.new('RGB',(20,20),'blue')),72,700,20,20)
    c.showPage();c.save();(out/name).write_bytes(buf.getvalue())
pdf('text.pdf','text');pdf('empty.pdf','empty');pdf('scanned.pdf','image')
w=PdfWriter();w.append(PdfReader(out/'text.pdf'));w.encrypt('fixture-password',algorithm='RC4-128')
with (out/'password.pdf').open('wb') as f:w.write(f)
# Encryption has a random file ID: preserve generated bytes rather than regenerating on each check.
manifest={'kind':'constructed public parser tests, not corpus', 'files':{p.name:{'bytes':p.stat().st_size,'sha256':hashlib.sha256(p.read_bytes()).hexdigest()} for p in sorted(out.iterdir()) if p.is_file() and p.name!='manifest.json'}}
(out/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
print(json.dumps(manifest,indent=2))
